const path = require("path");
const fs = require("fs");
const esbuild = require("esbuild");

const isWatch = process.argv.includes("--watch");
const srcEntry = path.join(__dirname, "src", "index.js");
const outBundle = path.join(__dirname, "dist", "nexa-editor.bundle.js");
const outPluginHtml = path.join(__dirname, "lib", "nexa-plugin.html");
// Standalone Lit vendor bundle for deployed public pages (nexa-runtime-client.js
// is hand-maintained plain JS, not part of the src/ esbuild pipeline, so it
// needs Lit as a separately-served <script> — see src/lit-vendor.js's own
// comment for why this can't just be an ES import at evaluation time).
const litVendorEntry = path.join(__dirname, "src", "lit-vendor.js");
const outLitVendorBundle = path.join(__dirname, "lib", "nexa-lit-vendor.bundle.js");

async function runBuild() {
    const startTime = Date.now();
    try {
        const result = await esbuild.build({
            entryPoints: [srcEntry],
            bundle: true,
            format: "iife",
            write: false,
            target: ["es2020"]
        });

        const code = result.outputFiles[0].text;

        // Ensure dist folder exists
        const distDir = path.join(__dirname, "dist");
        if (!fs.existsSync(distDir)) {
            fs.mkdirSync(distDir, { recursive: true });
        }
        fs.writeFileSync(outBundle, code, "utf8");

        // Write wrapped lib/nexa-plugin.html. The Lit vendor bundle is a
        // plain <script src> (served via RED.httpAdmin — see lib/nexa-plugin.js)
        // rather than folded into the bundle below — see src/lit-vendor.js's
        // comment for why.
        const htmlContent = `<script src="nexa-dashboard/_lit-vendor.js"></script>\n<script type="text/javascript">\n// Auto-generated by build.js — DO NOT EDIT MANUALLY.\n// Edit modular source files in src/ instead.\n${code}\n</script>\n`;
        fs.writeFileSync(outPluginHtml, htmlContent, "utf8");

        const litVendorResult = await esbuild.build({
            entryPoints: [litVendorEntry],
            bundle: true,
            format: "iife",
            write: false,
            target: ["es2020"]
        });
        fs.writeFileSync(outLitVendorBundle, litVendorResult.outputFiles[0].text, "utf8");

        console.log(`[build] Built nexa-plugin.html, nexa-editor.bundle.js & nexa-lit-vendor.bundle.js in ${Date.now() - startTime}ms`);
    } catch (e) {
        console.error("[build] Build error:", e);
    }
}

if (isWatch) {
    runBuild().then(() => {
        console.log("[build] Watching src/ for changes...");
        const srcDir = path.join(__dirname, "src");
        fs.watch(srcDir, { recursive: true }, (eventType, filename) => {
            if (filename && (filename.endsWith(".js") || filename.endsWith(".html"))) {
                console.log(`[build] Change detected in ${filename}, rebuilding...`);
                runBuild();
            }
        });
    });
} else {
    runBuild();
}
